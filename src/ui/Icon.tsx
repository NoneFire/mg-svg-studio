/** 图标统一走 @tita-agent/ui 同源的 lucide-react；这里的 name 是产品内的语义别名 */
const MAP: Record<string, LucideIcon> = {
  grid: LayoutGrid,
  play: Play,
  pause: Pause,
  stop: Square,
  skipBack: SkipBack,
  skipForward: SkipForward,
  more: Ellipsis,
  fit: Scan,
  upload: Upload,
  plus: Plus,
  minus: Minus,
  search: Search,
  trash: Trash2,
  copy: Copy,
  chevron: ChevronRight,
  chevronDown: ChevronDown,
  chevronUp: ChevronUp,
  chevronLeft: ChevronLeft,
  eye: Eye,
  eyeOff: EyeOff,
  sparkle: Sparkles,
  layers: Layers,
  animation: Spline,
  settings: Settings,
  reset: RotateCcw,
  history: History,
  undo: Undo2,
  redo: Redo2,
  close: X,
  loop: Repeat2,
  zoomIn: ZoomIn,
  zoomOut: ZoomOut,
  text: Type,
  shape: Shapes,
  mic: Mic,
  volume: Volume2,
  volumeOff: VolumeX,
  code: CodeXml,
  save: Save,
  check: Check,
  help: CircleHelp,
  sun: Sun,
  moon: Moon,
  folder: Folder,
  panelLeft: PanelLeft,
  panelRight: PanelRight,
}

export function Icon({ name, size = 16, className }: { name: string; size?: number; className?: string }) {
  const Cmp = MAP[name] || CircleHelp
  const solid = name === 'play' || name === 'pause' || name === 'stop'
  return <Cmp size={size} strokeWidth={1.7} className={className} fill={solid ? 'currentColor' : 'none'} aria-hidden />
}
